app.post('/api/invoices', auth, async (req, res) => {
  try {
    const {
      customerName,
      customerEmail,
      items,
      dueDate,
      notes,
      vatRate
    } = req.body || {};

    if (
      !customerName ||
      !Array.isArray(items) ||
      !items.length
    ) {
      return res.status(400).json({
        message: 'Customer and at least one item are required.'
      });
    }

    const clean = items.map((item) => ({
      description: String(
        item.description || 'Item'
      ).trim(),
      quantity: Math.max(
        1,
        Number(item.quantity) || 1
      ),
      price: Math.max(
        0,
        Number(item.price) || 0
      )
    }));

    if (
      clean.some(
        (item) =>
          !item.description ||
          item.price <= 0
      )
    ) {
      return res.status(400).json({
        message:
          'Each item needs a description and price.'
      });
    }

    const subtotal = clean.reduce(
      (sum, item) =>
        sum + item.quantity * item.price,
      0
    );

    const rate = Math.max(
      0,
      Math.min(
        100,
        Number(vatRate) || 0
      )
    );

    const invoice = {
      id: id('inv'),
      userId: req.user.id,
      number: `INV-${String(Date.now()).slice(-8)}`,
      customerName: String(customerName).trim(),
      customerEmail: String(customerEmail || '').trim(),
      items: clean,
      subtotal,
      total: subtotal * (1 + rate / 100),
      status: 'unpaid',
      dueDate: dueDate || '',
      notes: String(notes || ''),
      vatRate: rate,
      createdAt: new Date().toISOString()
    };

    res.status(201).json(
      await db.addInvoice(invoice)
    );
  } catch (err) {
    res.status(500).json({
      message: err.message
    });
  }
});

app.patch('/api/invoices/:id', auth, async (req, res) => {
  if (
    !['paid', 'unpaid', 'overdue'].includes(
      req.body.status
    )
  ) {
    return res.status(400).json({
      message: 'Invalid invoice status.'
    });
  }

  const invoice = await db.updateInvoice(
    req.params.id,
    req.user.id,
    req.body.status
  );

  if (!invoice) {
    return res.status(404).json({
      message: 'Invoice not found.'
    });
  }

  res.json(invoice);
});

app.get(
  '/api/invoices/:id/:type',
  auth,
  async (req, res) => {
    const invoices = await db.list(
      'invoices',
      req.user.id
    );

    const invoice = invoices.find(
      (item) => item.id === req.params.id
    );

    if (!invoice) {
      return res.status(404).end();
    }

    const user = await db.getUser(req.user.id);

    const buffer = await pdf(
      invoice,
      user,
      req.params.type === 'receipt'
    );

    res.set({
      'Content-Type': 'application/pdf',
      'Content-Disposition': `attachment; filename="Billora-${invoice.number}-${req.params.type}.pdf"`
    });

    res.send(buffer);
  }
);

