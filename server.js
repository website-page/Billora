const id = (prefix) =>
  `${prefix}_${Date.now()}_${Math.random().toString(36).slice(2, 8)}`;

const pub = (u) => ({
  id: u.id,
  name: u.name,
  email: u.email,
  businessName: u.businessName,
  plan: u.plan,
  phone: u.phone || '',
  address: u.address || '',
  currency: u.currency || 'NGN',
  createdAt: u.createdAt
});

const token = (u) =>
  jwt.sign(
    {
      id: u.id,
      email: u.email
    },
    JWT_SECRET,
    {
      expiresIn: '7d'
    }
  );

function auth(req, res, next) {
  const header = req.headers.authorization || '';
  const t = header.startsWith('Bearer ')
    ? header.slice(7)
    : null;

  if (!t) {
    return res.status(401).json({
      message: 'Authentication required.'
    });
  }

  try {
    req.user = jwt.verify(t, JWT_SECRET);
    next();
  } catch (err) {
    return res.status(401).json({
      message: 'Session expired. Please log in again.'
    });
  }
}

/* =========================================================
   PDF GENERATION
========================================================= */

function pdf(inv, u, receipt = false) {
  return new Promise((resolve, reject) => {
    const d = new PDFDocument({
      margin: 48
    });

    const chunks = [];

    d.on('data', (chunk) => chunks.push(chunk));

    d.on('end', () => {
      resolve(Buffer.concat(chunks));
    });

    d.on('error', reject);

    d.fontSize(24)
      .font('Helvetica-Bold')
      .text(u.businessName || 'Billora');

    d.fontSize(10)
      .font('Helvetica')
      .text(u.address || '');

    if (u.phone) {
      d.text(u.phone);
    }

    d.moveDown(2)
      .fontSize(22)
      .font('Helvetica-Bold')
      .text(receipt ? 'PAYMENT RECEIPT' : 'INVOICE');

    d.fontSize(10)
      .font('Helvetica')
      .text(
        `${inv.number} • ${new Date(inv.createdAt).toLocaleDateString()}`
      );

    d.moveDown()
      .fontSize(12)
      .font('Helvetica-Bold')
      .text('Bill to');

    d.font('Helvetica').text(inv.customerName);

    if (inv.customerEmail) {
      d.text(inv.customerEmail);
    }

    d.moveDown()
      .font('Helvetica-Bold')
      .text('Description                 Qty       Price        Total');

    d.moveDown(0.5);

    inv.items.forEach((item) => {
      d.font('Helvetica').text(
        `${String(item.description)
          .slice(0, 28)
          .padEnd(28)} ${String(item.quantity).padStart(3)}   ${Number(
          item.price
        ).toLocaleString()}   ${(Number(item.quantity) * Number(item.price)).toLocaleString()}`
      );
    });

    d.moveDown()
      .font('Helvetica-Bold')
      .text(
        `Subtotal: ${Number(inv.subtotal).toLocaleString()} ${u.currency}`
      );

    if (Number(inv.vatRate) > 0) {
      d.text(
        `VAT (${inv.vatRate}%): ${(
          Number(inv.total) - Number(inv.subtotal)
        ).toLocaleString()} ${u.currency}`
      );
    }

    d.fontSize(15).text(
      `TOTAL: ${Number(inv.total).toLocaleString()} ${u.currency}`
    );

    d.fontSize(10)
      .font('Helvetica')
      .moveDown()
      .text(`Status: ${String(inv.status || '').toUpperCase()}`);

    if (inv.dueDate) {
      d.text(`Due date: ${inv.dueDate}`);
    }

    if (inv.notes) {
      d.moveDown().text(inv.notes);
    }

    d.moveDown(2).text('Generated by Billora.');

    d.end();
  });
}

